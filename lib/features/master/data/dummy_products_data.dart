  // Helper generate local image PNG dengan badge visual elegan
  static Future<String?> generateProductImage({
    required String name,
    required String category,
    required Color color,
    required String shortCode,
  }) async {
    try {
      final appDocDir = await getApplicationDocumentsDirectory();
      final productsDir = Directory(p.join(appDocDir.path, 'products_images'));
      if (!await productsDir.exists()) {
        await productsDir.create(recursive: true);
      }

      final fileName = 'dummy_${shortCode.toLowerCase()}_${name.hashCode.abs()}.png';
      final filePath = p.join(productsDir.path, fileName);
      final file = File(filePath);

      if (await file.exists()) {
        return filePath;
      }

      final recorder = ui.PictureRecorder();
      final canvas = Canvas(recorder, const Rect.fromLTWH(0, 0, 300, 300));

      // Background Gradient
      final bgPaint = Paint()
        ..shader = ui.Gradient.linear(
          const Offset(0, 0),
          const Offset(300, 300),
          [
            color,
            color.withValues(alpha: 0.75),
          ],
        );
      canvas.drawRRect(
        RRect.fromRectAndRadius(const Rect.fromLTWH(0, 0, 300, 300), const Radius.circular(32)),
        bgPaint,
      );

      // Inner Light Card
      final cardPaint = Paint()
        ..color = Colors.white.withValues(alpha: 0.18)
        ..style = PaintingStyle.fill;
      canvas.drawCircle(const Offset(150, 130), 80, cardPaint);

      // Main Text / ShortCode
      final textPainter = TextPainter(
        text: TextSpan(
          text: shortCode.length > 4 ? shortCode.substring(0, 4) : shortCode,
          style: const TextStyle(
            color: Colors.white,
            fontSize: 48,
            fontWeight: FontWeight.bold,
            letterSpacing: 2,
          ),
        ),
        textDirection: TextDirection.ltr,
      );
      textPainter.layout();
      textPainter.paint(
        canvas,
        Offset(150 - textPainter.width / 2, 130 - textPainter.height / 2),
      );

      // Bottom Banner for Product Name
      final bannerPaint = Paint()..color = const Color(0xFF0F172A).withValues(alpha: 0.75);
      canvas.drawRRect(
        RRect.fromRectAndCorners(
          const Rect.fromLTWH(0, 220, 300, 80),
          bottomLeft: const Radius.circular(32),
          bottomRight: const Radius.circular(32),
        ),
        bannerPaint,
      );

      final namePainter = TextPainter(
        text: TextSpan(
          text: name.length > 22 ? '${name.substring(0, 20)}...' : name,
          style: const TextStyle(
            color: Colors.white,
            fontSize: 14,
            fontWeight: FontWeight.w600,
          ),
        ),
        textDirection: TextDirection.ltr,
        maxLines: 1,
      );
      namePainter.layout(maxWidth: 270);
      namePainter.paint(
        canvas,
        Offset(150 - namePainter.width / 2, 235),
      );

      final catPainter = TextPainter(
        text: TextSpan(
          text: category.toUpperCase(),
          style: TextStyle(
            color: Colors.white.withValues(alpha: 0.7),
            fontSize: 10,
            fontWeight: FontWeight.bold,
            letterSpacing: 1,
          ),
        ),
        textDirection: TextDirection.ltr,
      );
      catPainter.layout();
      catPainter.paint(
        canvas,
        Offset(150 - catPainter.width / 2, 260),
      );

      final picture = recorder.endRecording();
      final img = await picture.toImage(300, 300);
      final byteData = await img.toByteData(format: ui.ImageByteFormat.png);
      if (byteData != null) {
        final buffer = byteData.buffer.asUint8List();
        await file.writeAsBytes(buffer);
        return filePath;
      }
      return null;
    } catch (e) {
      return null;
    }
  }

